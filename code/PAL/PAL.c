#include "PAL.h"

/* ===========================================================================
 * 实现分发
 * ---------------------------------------------------------------------------
 * 各平台实现文件以「直接定义 pal_* 函数」的方式提供后端。编译时只需编译
 * PAL.c 即可（不要再单独把 WIN_file.c / PAL_generic.c 等加入编译列表，否则
 * 会出现符号重定义）。
 *
 * 后续新增平台（如 stm32）时，在下面新增一个 #elif 分支并指定对应目录即可，
 * PAL.c 本身保持不变。
 * =========================================================================== */
#if PLATFORM == CONFIG_WINDOWS
    #include "windows/WIN_std.c"
    #include "windows/WIN_syscall.c"
#else
    /* 默认后端：纯 C99 通用实现，适用于 Linux / stm32 等无 libc 或受限环境。
     * 若某平台需要特化，把它改成 #elif PLATFORM == CONFIG_XXX 分支。 */
    #include "generic/PAL_generic.c"
#endif
